/** Typographic SVG cover (original artwork, no external assets). */
export function coverSvg({ title, author, bg, fg, accent, rtl = false }) {
  const words = title.split(' ');
  const lines = [];
  let line = '';
  for (const w of words) {
    if ((line + ' ' + w).trim().length > 14) {
      lines.push(line.trim());
      line = w;
    } else {
      line = (line + ' ' + w).trim();
    }
  }
  if (line) lines.push(line.trim());
  const tx = rtl ? 720 : 80;
  const anchor = rtl ? ' direction="rtl"' : '';
  const titleSpans = lines
    .map(
      (l, i) =>
        `<text x="${tx}" y="${300 + i * 92}" font-size="72" font-family="Georgia, 'Times New Roman', serif" fill="${fg}"${anchor}>${l}</text>`,
    )
    .join('\n  ');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="1200" viewBox="0 0 800 1200">
  <rect width="800" height="1200" fill="${bg}"/>
  <rect x="80" y="160" width="120" height="8" fill="${accent}"/>
  ${titleSpans}
  <text x="${tx}" y="${330 + lines.length * 92}" font-size="34" font-family="Georgia, serif" fill="${accent}"${anchor}>${author}</text>
  <g transform="translate(80 1020)">
    <path d="M0 60 C 30 10, 90 10, 120 60 C 90 46, 30 46, 0 60 Z" fill="none" stroke="${accent}" stroke-width="6"/>
    <line x1="60" y1="18" x2="60" y2="60" stroke="${accent}" stroke-width="6"/>
  </g>
  <text x="80" y="1140" font-size="24" font-family="Georgia, serif" fill="${fg}" opacity="0.7">A ReadPort sample edition</text>
</svg>`;
}
